type ArtFrame = readonly [number, number, number]
const dynamicUrls = new Map<string, string>()
const dynamicFrames = new Map<string, ArtFrame>()

export function registerDynamicStandingArt(id: string, url: string, frame: ArtFrame = [50, -10, 420]) {
  dynamicUrls.set(id, url)
  dynamicFrames.set(id, frame)
}

export function hasStaticStandingArt(id: string) {
  return Object.hasOwn(schaledbIds, id) || Object.hasOwn(wikiUrls, id)
}

export function clearDynamicStandingArt() {
  dynamicUrls.clear()
  dynamicFrames.clear()
}

export function standingArtUrl(id: string): string | undefined {
  if (Object.hasOwn(schaledbIds, id)) return `https://schaledb.com/images/student/portrait/${schaledbIds[id]}.webp`
  return Object.hasOwn(wikiUrls, id) ? wikiUrls[id] : dynamicUrls.get(id)
}

